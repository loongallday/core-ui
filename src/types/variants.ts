/**
 * Variant type definitions for consistent component styling
 */

/**
 * Button variant types
 */
export type ButtonVariant = 
  | 'default'
  | 'destructive'
  | 'outline'
  | 'secondary'
  | 'ghost'
  | 'link'

/**
 * Button size types
 */
export type ButtonSize = 'default' | 'sm' | 'lg' | 'icon' | 'xs' | 'xl'

/**
 * Badge variant types
 */
export type BadgeVariant =
  | 'default'
  | 'secondary'
  | 'destructive'
  | 'outline'
  | 'success'
  | 'warning'

/**
 * Alert variant types
 */
export type AlertVariant = 'default' | 'destructive' | 'success' | 'warning' | 'info'

/**
 * Input variant types
 */
export type InputVariant = 'default' | 'error' | 'success'

/**
 * Card variant types
 */
export type CardVariant = 'default' | 'elevated' | 'outline' | 'ghost'

/**
 * Toast variant types
 */
export type ToastVariant = 'default' | 'destructive' | 'success' | 'warning'

/**
 * Common size scale
 */
export type CommonSize = 'xs' | 'sm' | 'default' | 'md' | 'lg' | 'xl'

/**
 * Spacing scale
 */
export type Spacing = 'none' | 'xs' | 'sm' | 'md' | 'lg' | 'xl' | '2xl'

/**
 * Border radius scale
 */
export type Radius = 'none' | 'sm' | 'md' | 'lg' | 'xl' | 'full'

/**
 * Shadow scale
 */
export type Shadow = 'none' | 'sm' | 'md' | 'lg' | 'xl' | '2xl'

